from typing import Final

class BookAlreadyIssuedError(Exception):
    """Книга уже выдана и не может быть выдана повторно."""

class BookNotIssuedError(Exception):
    """Книга уже доступна и не может быть возвращена."""


class Book:
    """Класс Book с полной инкапсуляцией состояния и защитой инвариантов."""
    # Описывает книгу и управляет её статусом (доступна/выдана)

    def __init__(self, isbn: str, title: str, author: str) -> None:
        # Конструктор принимает неизменяемые метаданные книги
        self.__isbn: Final[str] = isbn
        # ISBN фиксируется как финальный атрибут — не подлежит изменению
        self.__title: Final[str] = title
        # Название книги также неизменяемо после создания
        self.__author: Final[str] = author
        # Автор фиксируется и не должен меняться в жизненном цикле книги
        self.__is_available: bool = True
        # Внутренний флаг доступности: True — на полке, False — выдана

    @property
    def is_available(self) -> bool:
        """Публичный геттер для проверки доступности книги."""
        # Позволяет внешнему коду узнать статус, но не менять его
        return self.__is_available

    @property
    def isbn(self) -> str:
        """Геттер для ISBN — метаданные доступны только для чтения."""
        # Обеспечивает доступ к уникальному идентификатору без возможности правки
        return self.__isbn

    @property
    def title(self) -> str:
        """Геттер для названия книги — неизменяемый атрибут."""
        # Предоставляет название, запрещая любые изменения извне
        return self.__title

    @property
    def author(self) -> str:
        """Геттер для автора — неизменяемый атрибут."""
        # Возвращает имя автора, сохраняя инвариант неизменности метаданных
        return self.__author

    def issue(self) -> None:
        """Выдать книгу читателю — меняет статус с проверки инварианта."""
        # Метод реализует правило: нельзя выдать уже выданную книгу
        if not self.__is_available:
            # Проверяем, доступна ли книга перед выдачей
            raise BookAlreadyIssuedError("Книга уже выдана и не может быть выдана повторно.")
            # Нарушение инварианта приводит к исключению с понятным сообщением
        self.__is_available = False
        # Если проверка пройдена, помечаем книгу как выданную

    def return_book(self) -> None:
        """Вернуть книгу в библиотеку - меняет статус с проверки инварианта."""
        # Реализует правило: нельзя вернуть книгу, которая не была выдана
        if self.__is_available:
            # Проверяем текущий статус перед операцией возврата
            raise BookNotIssuedError("Книга уже доступна и не может быть возвращена.")
            # Нарушение инварианта вызывает исключение с пояснением
        self.__is_available = True
        # При корректном вызове возвращаем книгу на полку

    def __repr__(self) -> str:
        """Строковое представление объекта для удобной отладки в консоли."""
        # Помогает быстро увидеть состояние книги при выводе в консоль
        status = "доступна" if self.__is_available else "выдана"
        # Формируем читаемый статус для отображения
        return f"Book(isbn={self.__isbn!r}, title={self.__title!r}, author={self.__author!r}, status={status})"
        # Возвращаем строку с основными данными и текущим статусом
